/**
 * N137 · G1 (v7 UX plan r3, `04` §3.2 generator 5): the Android colours, generated from the kit's design tokens
 * (src/ui/v7/design-tokens.json), so the app's native surfaces (window and splash background, notification accent,
 * theme colours) use the kit's exact Day and Night values and cannot drift from the web. Writes
 * android/app/src/main/res/values/colors.xml and values-night/colors.xml; run by `npm run build:android`, and the asset
 * lint (scripts/brand/asset-lint.mjs) fails a build whose committed files differ from what this would write.
 */
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {dirname, join} from 'node:path';

const root = process.cwd();
const TOKENS = join(root, 'src', 'ui', 'v7', 'design-tokens.json');
const RES = join(root, 'android', 'app', 'src', 'main', 'res');

/** Each Android colour name and the token it comes from, per mode. Names are the ones the app already uses. */
export const ANDROID_COLOURS = {
  day: [
    ['lemma_paper', 'surface.page', 'the page: window and splash background'],
    ['lemma_ink', 'action.bg', 'the brand indigo: notification accent'],
    ['colorPrimary', 'action.bg', 'theme primary'],
    ['colorPrimaryDark', 'text.primary', 'theme primary dark (status bar on old Android)'],
    ['colorAccent', 'action.bg', 'theme accent'],
  ],
  night: [
    ['lemma_paper', 'surface.page', 'the Night page'],
    ['lemma_ink', 'action.bg', 'the Night brand indigo'],
  ],
};

export function readTokens(path = TOKENS) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

/** The colors.xml text for one mode. Pure: same tokens, same text. */
export function colorsXml(tokens, mode) {
  const raw = tokens.raw[mode];
  const lines = ANDROID_COLOURS[mode].map(([name, key, what]) => {
    const value = raw[key]?.$value;
    if (!/^#[0-9A-Fa-f]{6}$/.test(value ?? '')) throw new Error(`design-tokens.json: raw.${mode}.${key} is not a #RRGGBB colour`);
    return `    <!-- ${what}: ${key} -->\n    <color name="${name}">${value.toUpperCase()}</color>`;
  });
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by scripts/brand/android-colors.mjs from src/ui/v7/design-tokens.json (${mode}). Change the tokens, not this file. -->\n<resources>\n${lines.join('\n')}\n</resources>\n`;
}

export const COLOR_FILES = {day: join(RES, 'values', 'colors.xml'), night: join(RES, 'values-night', 'colors.xml')};

export function generate(tokens = readTokens()) {
  for (const [mode, path] of Object.entries(COLOR_FILES)) {
    mkdirSync(dirname(path), {recursive: true});
    writeFileSync(path, colorsXml(tokens, mode));
  }
  return Object.values(COLOR_FILES);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const files = generate();
  console.log('Generated Android colours: ' + files.map(file => file.slice(root.length + 1)).join(', '));
}
