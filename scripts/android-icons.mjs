/**
 * N123 · the Android app's launcher, themed (monochrome), notification and legacy icons, generated from the same
 * Notebook mark as the web icons (scripts/brand/lemma-mark.mjs, Owner decision D3 = C). Writes into android/app/src/
 * main/res/ and is run by `npm run build:android`; the outputs are committed so Android Studio builds work as cloned.
 * No native canvas, font or image dependencies.
 */
import {mkdirSync,writeFileSync} from 'node:fs';
import {dirname,join} from 'node:path';
import {deflateSync} from 'node:zlib';
import {rasterMark,ellPathData,MARK_THEMES} from './brand/lemma-mark.mjs';

const res=join(process.cwd(),'android','app','src','main','res');
const DENSITIES={mdpi:1,hdpi:1.5,xhdpi:2,xxhdpi:3,xxxhdpi:4};

function crc32(buffer){
 let crc=-1;
 for(const byte of buffer){crc^=byte;for(let i=0;i<8;i++)crc=(crc>>>1)^(-(crc&1)&0xEDB88320);}
 return (crc^(-1))>>>0;
}
function chunk(name,data){
 const label=Buffer.from(name,'ascii'),length=Buffer.alloc(4),crc=Buffer.alloc(4);
 length.writeUInt32BE(data.length,0);crc.writeUInt32BE(crc32(Buffer.concat([label,data])),0);
 return Buffer.concat([length,label,data,crc]);
}
export function encodePng(size,rgba){
 const bytes=Buffer.alloc(size*(size*4+1));
 for(let y=0;y<size;y++){const row=y*(size*4+1);bytes[row]=0;for(let x=0;x<size*4;x++)bytes[row+1+x]=rgba[y*size*4+x];}
 const header=Buffer.alloc(13);header.writeUInt32BE(size,0);header.writeUInt32BE(size,4);header[8]=8;header[9]=6;
 return Buffer.concat([Buffer.from('89504e470d0a1a0a','hex'),chunk('IHDR',header),chunk('IDAT',deflateSync(bytes,{level:9})),chunk('IEND',Buffer.alloc(0))]);
}
/** Place a square RGBA image centred on a transparent canvas. */
function inset(canvas,image,size){
 const out=new Uint8ClampedArray(canvas*canvas*4),offset=Math.round((canvas-size)/2);
 for(let y=0;y<size;y++)for(let x=0;x<size;x++){const s=(y*size+x)*4,d=((y+offset)*canvas+x+offset)*4;for(let k=0;k<4;k++)out[d+k]=image[s+k];}
 return out;
}
/** Multiply alpha by a circle (the legacy round icon). */
function round(image,size){
 const out=new Uint8ClampedArray(image);
 for(let y=0;y<size;y++)for(let x=0;x<size;x++){
  const d=Math.hypot(x+0.5-size/2,y+0.5-size/2),a=Math.max(0,Math.min(1,size/2-d+0.5)),o=(y*size+x)*4+3;out[o]=Math.round(out[o]*a);
 }
 return out;
}
function write(path,data){mkdirSync(dirname(path),{recursive:true});writeFileSync(path,data);}

export function generate(){
 const written=[];
 for(const [name,scale] of Object.entries(DENSITIES)){
  // Adaptive foreground: 108 dp layer, the full-bleed mark in the visible 72 dp (the launcher's mask crops it).
  const layer=Math.round(108*scale),visible=Math.round(72*scale);
  const fg=join(res,'mipmap-'+name,'ic_launcher_foreground.png');
  write(fg,encodePng(layer,inset(layer,rasterMark({size:visible,theme:'day',layout:'full'}),visible)));
  // Legacy icons (Android 7): a rounded page and a round one.
  const legacy=Math.round(48*scale),layout=legacy<64?'simple':'full';
  write(join(res,'mipmap-'+name,'ic_launcher.png'),encodePng(legacy,rasterMark({size:legacy,theme:'day',layout,background:'rounded'})));
  write(join(res,'mipmap-'+name,'ic_launcher_round.png'),encodePng(legacy,round(rasterMark({size:legacy,theme:'day',layout}),legacy)));
  written.push(fg);
 }
 // Themed icon (Android 13+): the ℓ alone; the launcher tints it. Inner 72 dp of a 108 dp layer, so a 1536 viewport.
 write(join(res,'drawable','ic_launcher_monochrome.xml'),
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/android-icons.mjs from the Notebook mark (N123). -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="1536" android:viewportHeight="1536">\n <group android:translateX="256" android:translateY="256">\n  <path android:fillColor="#FF000000" android:pathData="${ellPathData('simple',1024)}"/>\n </group>\n</vector>\n`);
 // Notification small icon: the same ℓ, white (Android masks it to a silhouette).
 write(join(res,'drawable','ic_stat_lemma.xml'),
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/android-icons.mjs from the Notebook mark (N123). -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="1024" android:viewportHeight="1024">\n <path android:fillColor="#FFFFFFFF" android:pathData="${ellPathData('simple',1024)}"/>\n</vector>\n`);
 write(join(res,'values','ic_launcher_background.xml'),
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/android-icons.mjs: the Day paper of the Notebook mark. -->\n<resources>\n    <color name="ic_launcher_background">${MARK_THEMES.day.page}</color>\n</resources>\n`);
 return written;
}

if(import.meta.url===`file://${process.argv[1]}`){
 const files=generate();
 console.log('Generated Android icons ('+files.length+' densities)');
}
