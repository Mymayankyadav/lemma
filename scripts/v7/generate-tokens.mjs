// Generate Day/Night/HC CSS and Figma variable interchange from one DTCG source.
import {readFileSync,writeFileSync} from 'node:fs';
const generate=function generate(document){
 // Each of the eight subject families has a stroke and tile. Keep the source roles and named palette in sync.
 for(const [family,name] of Object.entries(document.subjectPalette.familyAssignments))for(const [mode,theme] of [['day','light'],['night','dark']])for(const [suffix,part] of [['','stroke'],['-subtle','tile']]){
  if(document.raw[mode]['subject.'+family+suffix].$value.toLowerCase()!==document.subjectPalette.colors[name][theme][part].toLowerCase())throw new Error('Subject palette mismatch: '+mode+' '+family+suffix);
 }
 const keys=Object.keys(document.role);
 const hc=(key,mode)=>{
  if(mode.endsWith("-hc")){if(key==="text.secondary"||key==="text.tertiary")return document.raw[mode.startsWith("night")?"night":"day"]["text.primary"].$value;
   if(key==="border.default")return document.raw[mode.startsWith("night")?"night":"day"]["border.strong"].$value;
  }
  return document.raw[mode.startsWith("night")?"night":"day"][key].$value;
 };
 const modes=["day","night","day-hc","night-hc"];
 const sels=['[data-v7][data-theme="graph"]','[data-v7][data-theme="graph-night"]','[data-v7][data-theme="graph"][data-contrast="high"]','[data-v7][data-theme="graph-night"][data-contrast="high"]'];
 let css="/* GENERATED by scripts/v7/generate-tokens.mjs — change design-tokens.json, not this file. */\n";
 for(let i=0;i<modes.length;i++){const mode=modes[i]; css+=`${sels[i]} {\n`;
  // Native/Figma colours are flattened on page paper; CSS retains the owner's exact translucent selection tint.
  for(const k of keys)css+=`  --v7-role-${k.replaceAll(".","-")}: ${k==='selection.subtle'?'var(--accent-subtle)':k==='surface.track'?'var(--progress-track)':hc(k,mode)};\n`;
  // K2 (Night critique v2): role tokens and per-mode effects only. No legacy aliases and no unread component tier.
  if(i<2)for(const [name,value] of Object.entries(document.foundation.effects[mode]))css+=`  --v7-${name}: ${value};\n`;
  css+=`}\n`;
 }
 css+=`[data-v7][data-theme="graph-night"] :where([data-v7-lifted],.v7-menu,.v7-picker-list,.v7-toast,.v7-app-toast,.v7-info-tip) {
  --v7-role-surface-overlay: var(--v7-role-surface-lifted);
  --v7-role-surface-raised: var(--v7-role-surface-lifted);
  --v7-role-surface-muted: var(--v7-role-state-lifted-hover);
  --v7-role-surface-muted-hover: var(--v7-role-state-lifted-hover);
  --v7-role-state-hover: var(--v7-role-state-lifted-hover);
  --v7-role-text-tertiary: var(--v7-role-text-secondary);
}
`;
 const foundations=document.foundation;
 css+="[data-v7] {\n";
 for(const [key,role] of Object.entries(foundations.role)) {
  const name=role.$value.slice("{foundation.raw.".length,-1);
  css+=`  --v7-${key}: ${foundations.raw[name].$value};\n`;
 }
 css+=`  color:var(--v7-role-text-primary);background:var(--v7-role-surface-page);font:400 var(--v7-type-body)/var(--v7-leading-body) var(--v7-sans);font-variant-numeric:tabular-nums lining-nums;\n}\n[data-v7][data-theme="graph"]{color-scheme:light;}[data-v7][data-theme="graph-night"]{color-scheme:dark;}\n`;
 // N157 · V23: control heights follow the pointer, not the width. The full touch size at every width; 40 px only for a
 // fine pointer (a mouse or trackpad) on a window of 700 px or more.
 for(const [viewport,query] of [["tablet","min-width:700px"],["desktop","min-width:1100px"],["fine","min-width:700px) and (pointer:fine"]]) {
  css+=`@media(${query}){[data-v7]{\n`;
  for(const [key,role] of Object.entries(foundations.role)) {
   const value=role.$extensions?.["lemma.viewport"]?.[viewport];
   if(value)css+=`  --v7-${key}: ${value};\n`;
  }
  css+="}}\n";
 }
 css+=`[data-v7][data-v7-density="compact"]{--v7-button:40px;--v7-field:40px;--v7-row:56px;}\n[data-v7][data-contrast="high"]{--v7-focus-width:3px;}\n`;
 const figma={name:"Lemma v7 Constellation / Figma variable interchange",modes,collections:[]};
 const rawVariables=keys.map(key=>({name:key.replaceAll(".","/"),type:"COLOR",modes:Object.fromEntries(modes.map(mode=>[mode,document.raw[mode.startsWith("night")?"night":"day"][key].$value]))}));
 const roles=Object.entries(document.role).map(([key,value])=>({name:key.replaceAll(".","/"),type:"COLOR",description:value.$description,modes:Object.fromEntries(modes.map(mode=>[mode,hc(key,mode)]))}));
 const components=Object.entries(document.component).map(([key,value])=>({name:key.replaceAll(".","/"),type:"COLOR",alias:value.$value}));
 figma.collections.push({name:"Raw",variables:rawVariables},{name:"Role",variables:roles},{name:"Component",variables:components});
 for(const [key,value] of Object.entries(document.foundation.raw))figma.collections[0].variables.push({name:"foundation/"+key,type:value.$type,value:value.$value});
 for(const [key,value] of Object.entries(document.foundation.role))figma.collections[1].variables.push({name:"foundation/"+key,type:value.$type,alias:value.$value,description:value.$description});
 for(const name of Object.keys(document.foundation.effects.day)){
  figma.collections[0].variables.push({name:"effects/"+name,type:"STRING",modes:Object.fromEntries(modes.map(mode=>[mode,document.foundation.effects[mode.startsWith("night")?"night":"day"][name]]))});
  figma.collections[1].variables.push({name:"effects/"+name,type:"STRING",alias:"{foundation.effects."+name+"}"});
 }
 css="@layer theme, base, components, utilities, lemma-app, v7-tokens, v7-reset, v7-components, v7-gallery, v7-states, v7-accessibility;\n@layer v7-tokens {\n"+css+"\n}\n";
 // The public palette also reaches legacy routes and the shell before v7 loads.
 const publicValues = mode => ({...document.palette[mode],...Object.fromEntries(Object.entries(document.subjectPalette.colors).flatMap(([name, values])=>Object.entries(values[mode==='day'?'light':'dark']).map(([part,value])=>['subject-'+name+'-'+part,value])))});
 const palette = Object.keys(document.palette).map(mode => {
  const selector = mode === 'day' ? ':root, [data-v7][data-theme="graph"]' : ':root[data-theme="dark"], :root[data-theme="graph-night"], [data-v7][data-theme="graph-night"]';
  return `${selector} {\n${Object.entries(publicValues(mode)).map(([name,value])=>`  --${name}: ${value};`).join('\n')}\n}`;
 }).join('\n');
 const systemNight = `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n${Object.entries(publicValues('night')).map(([name,value])=>`    --${name}: ${value};`).join('\n')}\n  }\n}\n`;
 return {css,figma:JSON.stringify(figma,null,2)+"\n",palette:'/* GENERATED by scripts/v7/generate-tokens.mjs from design-tokens.json. */\n'+palette+'\n'+systemNight};
};
const source=JSON.parse(readFileSync('src/ui/v7/design-tokens.json','utf8'));
const result=generate(source);
const outputs=[['src/ui/v7/tokens.css',result.css],['src/ui/v7/figma-variables.json',result.figma],['src/styles/palette.css',result.palette]];
if(process.argv.includes('--check')){let bad=false;for(const [path,value] of outputs){if(readFileSync(path,'utf8')!==value){console.error(path+' is out of date');bad=true;}}if(bad)process.exit(1);}else for(const [path,value] of outputs)writeFileSync(path,value);

// Keep the reviewable, standalone token sheet beside the generated CSS and Figma values.
await import('./generate-token-preview.mjs');

