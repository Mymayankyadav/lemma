// Generate Day/Night/HC CSS and Figma variable interchange from one DTCG source.
import {readFileSync,writeFileSync} from 'node:fs';
const generate=function generate(document){
 const keys=Object.keys(document.role);
 const hc=(key,mode)=>{
  if(mode.endsWith("-hc")){if(key==="text.secondary"||key==="text.tertiary")return document.raw[mode.startsWith("night")?"night":"day"]["text.primary"].$value;
   if(key==="border.default")return document.raw[mode.startsWith("night")?"night":"day"]["border.strong"].$value;
  }
  return document.raw[mode.startsWith("night")?"night":"day"][key].$value;
 };
 const modes=["day","night","day-hc","night-hc"];
 const sels=['[data-v7][data-theme="graph"]','[data-v7][data-theme="graph-night"]','[data-v7][data-theme="graph"][data-contrast="high"]','[data-v7][data-theme="graph-night"][data-contrast="high"]'];
 const subjectNames=["analysis","algebra","topology","number-theory","geometry","logic","probability","combinatorics"];
 const compat={"bg":"surface.page","bg-raised":"surface.raised","bg-overlay":"surface.overlay","bg-inset":"surface.sunken","ink":"text.primary","ink-2":"text.secondary","ink-3":"text.tertiary","accent":"link.fg","accent-fill":"action.bg","accent-fill-hi":"action.hover","good":"status.success","warning":"status.warning","control-border":"border.default","surface-border":"border.subtle","control-track":"surface.muted","disabled-ink":"text.disabled","disabled-bg":"surface.muted","focus-ring":"focus.ring","good-fill":"status.success"};
 let css="/* GENERATED by scripts/v7/generate-tokens.mjs — change design-tokens.json, not this file. */\n";
 for(let i=0;i<modes.length;i++){const mode=modes[i]; css+=`${sels[i]} {\n`;
  for(const k of keys)css+=`  --v7-role-${k.replaceAll(".","-")}: ${hc(k,mode)};\n`;
  for(const [k,v] of Object.entries(document.component))css+=`  --v7-component-${k.replaceAll(".","-")}: var(--v7-role-${v.$value.slice(6,-1).replaceAll(".","-")});\n`;
  if(i<2){for(const [k,v] of Object.entries(compat))css+=`  --v7-${k}: var(--v7-role-${v.replaceAll(".","-")});\n`;
   for(let j=0;j<subjectNames.length;j++)css+=`  --v7-subject-${j+1}: var(--v7-role-subject-${subjectNames[j]});\n`;
   css+=`  --v7-wash: var(--v7-role-surface-muted);\n  --v7-wash-strong: var(--v7-role-surface-muted-hover);\n  --v7-line: var(--v7-role-border-subtle);\n  --v7-line-strong: var(--v7-role-border-default);\n  --v7-white: var(--v7-role-text-on-action);\n  --v7-glass: var(--v7-role-surface-overlay);\n`;
   for(const [name,value] of Object.entries(document.foundation.effects[mode]))css+=`  --v7-${name}: ${value};\n`;
  }
  css+=`}\n`;
 }
 const foundations=document.foundation;
 css+="[data-v7] {\n";
 for(const [key,role] of Object.entries(foundations.role)) {
  const name=role.$value.slice("{foundation.raw.".length,-1);
  css+=`  --v7-${key}: ${foundations.raw[name].$value};\n`;
 }
 css+=`  color:var(--v7-role-text-primary);background:var(--v7-role-surface-page);font:400 var(--v7-size-3)/var(--v7-leading-3) var(--v7-sans);font-variant-numeric:tabular-nums lining-nums;\n}\n[data-v7][data-theme="graph"]{color-scheme:light;}[data-v7][data-theme="graph-night"]{color-scheme:dark;}\n`;
 for(const [viewport,width] of [["tablet",700],["desktop",1100]]) {
  css+=`@media(min-width:${width}px){[data-v7]{\n`;
  for(const [key,role] of Object.entries(foundations.role)) {
   const value=role.$extensions?.["lemma.viewport"]?.[viewport];
   if(value)css+=`  --v7-${key}: ${value};\n`;
  }
  css+="}}\n";
 }
 css+=`[data-v7][data-density="compact"]{--v7-button:40px;--v7-field:40px;--v7-row:56px;}\n[data-v7][data-contrast="high"]{--v7-focus-width:3px;--v7-line-strong:var(--v7-role-border-strong);}\n`;
 const figma={name:"Lemma v7 Constellation / Figma variable interchange",modes,collections:[]};
 const rawVariables=keys.map(key=>({name:key.replaceAll(".","/"),type:"COLOR",modes:Object.fromEntries(modes.map(mode=>[mode,document.raw[mode.startsWith("night")?"night":"day"][key].$value]))}));
 const roles=Object.entries(document.role).map(([key,value])=>({name:key.replaceAll(".","/"),type:"COLOR",description:value.$description,modes:Object.fromEntries(modes.map(mode=>[mode,hc(key,mode)]))}));
 const components=Object.entries(document.component).map(([key,value])=>({name:key.replaceAll(".","/"),type:"COLOR",alias:value.$value}));
 figma.collections.push({name:"Raw",variables:rawVariables},{name:"Role",variables:roles},{name:"Component",variables:components});
 for(const [key,value] of Object.entries(document.foundation.raw))figma.collections[0].variables.push({name:"foundation/"+key,type:value.$type,value:value.$value});
 for(const [key,value] of Object.entries(document.foundation.role))figma.collections[1].variables.push({name:"foundation/"+key,type:value.$type,alias:value.$value,description:value.$description});
 for(const name of Object.keys(document.foundation.effects.day)){
  figma.collections[0].variables.push({name:"effects/"+name,type:"STRING",modes:Object.fromEntries(modes.map(mode=>[mode,document.foundation.effects[mode.startsWith("night")?"night":"day"][name]]))});
  figma.collections[1].variables.push({name:"effects/"+name,type:"STRING",alias:"{foundation.effects."+name+"}"});
 }
 css="@layer theme, base, components, utilities, lemma-app, v7-tokens, v7-reset, v7-components, v7-gallery, v7-states, v7-accessibility;\n@layer v7-tokens {\n"+css+"\n}\n";
 return {css,figma:JSON.stringify(figma,null,2)+"\n"};
};
const source=JSON.parse(readFileSync('src/ui/v7/design-tokens.json','utf8'));
const result=generate(source);
const outputs=[['src/ui/v7/tokens.css',result.css],['src/ui/v7/figma-variables.json',result.figma]];
if(process.argv.includes('--check')){let bad=false;for(const [path,value] of outputs){if(readFileSync(path,'utf8')!==value){console.error(path+' is out of date');bad=true;}}if(bad)process.exit(1);}else for(const [path,value] of outputs)writeFileSync(path,value);

