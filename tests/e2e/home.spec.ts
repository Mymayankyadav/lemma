import {test,expect} from '@playwright/test'

test.beforeEach(async({page})=>{
 await page.route('https://fonts.googleapis.com/**',route=>route.fulfill({body:''}))
 await page.route('https://fonts.gstatic.com/**',route=>route.fulfill({body:''}))
 await page.goto('./?demo=1#/')
})

test('today desk shows resume, reviews, proposals and projects with no runtime errors',async({page})=>{
 const errors:string[]=[]
 page.on('pageerror',error=>errors.push(error.message))
 page.on('console',message=>{if(message.type()==='error')errors.push(message.text())})
 await expect(page.getByRole('heading',{name:'Home',level:1})).toBeVisible()
 await expect(page.getByRole('region',{name:'Resume where you stopped'})).toContainText('Real Analysis · step 2 of 4')
 await expect(page.getByRole('region',{name:'Review',exact:true}).locator('p.text-body').first()).toContainText('23 due')
 await expect(page.getByRole('link',{name:/Review 6 tutor proposals/i})).toBeVisible()
 await expect(page.getByText('6 tutor proposals awaiting your decision')).toBeVisible()
 await expect(page.getByRole('region',{name:'Resume where you stopped'})).not.toContainText('Why is a finite subcover enough to separate x from K?')
 await expect(page.getByRole('article',{name:'Goal progress for Real Analysis'}).getByRole('link',{name:'Real Analysis',exact:true})).toBeVisible()
 const goals=page.getByRole('region',{name:'Distance to your goals'})
 await expect(goals.getByRole('article',{name:'Goal progress for Topology'})).toBeVisible()
 await expect(goals.getByRole('article',{name:'Goal progress for Linear Algebra'})).toBeVisible()
 await expect(goals.getByRole('link',{name:'All paths'})).toBeVisible()
 await expect(page.getByRole('region',{name:'Projects',exact:true})).toHaveCount(0)
 await expect(page.getByRole('navigation',{name:'Desk actions'}).getByRole('link')).toHaveCount(3)
 await expect(page.getByRole('navigation',{name:'Main navigation'}).getByRole('link')).toHaveCount(4)
 await page.screenshot({path:'test-results/screens/home.png',fullPage:true})
 expect(errors).toEqual([])
})

test('Continue is a clipped 64px passive row with a single Copy action',async({page,context})=>{
 await context.grantPermissions(['clipboard-read','clipboard-write'])
 const handoff=page.getByRole('region',{name:'Resume where you stopped'})
 await expect(handoff).toBeVisible()
 await expect(handoff).toContainText('Real Analysis · step 2 of 4')
 const box=await handoff.boundingBox()
 expect(box).not.toBeNull()
 expect(box!.height).toBeGreaterThanOrEqual(64)
 await expect(handoff.getByRole('button',{name:'Copy resume prompt'}).locator('svg')).toHaveCount(1)
 await expect(handoff).toContainText('Compactness')
 await expect(page.getByRole('button',{name:'Resume',exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Choose chat app or copy prompt'})).toHaveCount(0)
 await handoff.getByRole('button',{name:'Copy resume prompt'}).click()
 await expect(page.getByText('Prompt copied',{exact:true})).toBeVisible()
 expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe('Resume Real Analysis')
 const start=page.getByRole('link',{name:'Start review of 23 cards'})
 await expect(start).toBeVisible()
 expect((await start.boundingBox())!.height).toBeGreaterThanOrEqual(44)
 await expect(page.getByRole('region',{name:'Study handoff'}).locator('.slab')).toHaveCount(0)
 await page.screenshot({path:'test-results/screens/home-last-chat.png',fullPage:true})
})

test('home shortcuts navigate to review, proposals and the project path',async({page})=>{
 await page.getByRole('link',{name:/Start review of 23 cards/i}).click()
 await expect(page).toHaveURL(/#\/review$/)
 await page.goto('./?demo=1#/')
 await page.getByRole('link',{name:/Review 6 tutor proposals/i}).click()
 await expect(page).toHaveURL(/#\/proposals$/)
 await page.goto('./?demo=1#/')
 await page.getByRole('article',{name:'Goal progress for Real Analysis'}).getByRole('link',{name:'Real Analysis',exact:true}).click()
 await expect(page).toHaveURL(/#\/p\/real-analysis$/)
})

for(const theme of ['graph','graph-night'] as const){
 test(`LOOK-3c goal-first Today and one-link Route: ${theme}`,async({page})=>{
  await page.goto(`./?demo=1&theme=${theme}#/`)
  const goals=page.getByRole('region',{name:'Distance to your goals'})
  const cards=page.getByRole('region',{name:'Review',exact:true})
  await expect(goals).toBeVisible()
  await expect(cards).toBeVisible()
  await expect(page.locator('[aria-label="Seven-day review forecast"]')).toBeVisible()
  await expect(page.locator('[aria-label="Seven-day review forecast"] .grid > div')).toHaveCount(7)
  await expect(page.locator('[aria-label="Due cards by project"]')).toHaveCount(0)
  const order=await page.evaluate(()=>{
   const a=document.querySelector('[aria-label="Distance to your goals"]')
   const b=document.querySelector('[aria-label="Review"]')
   return !!(a&&b&&(a.compareDocumentPosition(b)&Node.DOCUMENT_POSITION_FOLLOWING))
  })
  expect(order).toBe(true)
  const algebra=goals.getByRole('article',{name:/Goal progress for Real Analysis/})
  await expect(algebra.locator('[data-goal-now]')).toContainText('3 of 12')
  const timeline=algebra.locator('[data-route-mode="today"]')
  await expect(timeline.getByRole('link')).toHaveAttribute('aria-label',/open current checkpoint CP4/)
  await page.screenshot({path:`test-results/screens/review/ui5b-goals-${theme}.png`,fullPage:true})
  await expect(timeline.getByRole('button')).toHaveCount(0)
  await timeline.getByRole('link').click()
  await expect(page).toHaveURL(/#\/p\/real-analysis\/cp\//)
 })
}
