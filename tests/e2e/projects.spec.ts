import {test,expect} from '@playwright/test'

test.beforeEach(async({page})=>{
 await page.route('https://fonts.googleapis.com/**',route=>route.fulfill({body:''}))
 await page.route('https://fonts.gstatic.com/**',route=>route.fulfill({body:''}))
})
test('Projects shows featured work, other projects and Atlas without errors',async({page})=>{
 const errors:string[]=[]
 page.on('pageerror',error=>errors.push(error.message))
 await page.goto('./?demo=1#/projects')
 await expect(page.getByRole('heading',{name:'Projects',level:1})).toBeVisible()
 await expect(page.getByRole('link',{name:'Real Analysis',exact:true})).toBeVisible()
 await expect(page.getByText('Compactness, step 2')).toBeVisible()
 await expect(page.getByRole('link',{name:/Atlas/i})).toBeVisible()
 await page.screenshot({path:'test-results/screens/projects-dashboard.png',fullPage:true})
 expect(errors).toEqual([])
})
test('creates a project with goal, subject and teaching style',async({page})=>{
 await page.goto('./?demo=1#/projects/new')
 await expect(page.getByRole('heading',{name:'New project',level:1})).toBeVisible()
 await page.getByRole('textbox',{name:'Name'}).fill('Complex Analysis')
 await page.getByRole('radiogroup',{name:'Subject'}).getByRole('radio',{name:'Analysis',exact:true}).click()
 await page.getByRole('textbox',{name:'Goal'}).fill('Prove Cauchy integral theorem and understand residues.')
 await page.getByRole('radiogroup',{name:'Teaching style'}).getByRole('radio',{name:'Proof workshop'}).click()
 await page.screenshot({path:'test-results/screens/new-project.png',fullPage:true})
 await page.getByRole('button',{name:'Create project'}).click()
 await expect(page).toHaveURL(/#\/p\/complex-analysis$/)
 await expect(page.getByText(/Project created/)).toBeVisible()
})
test('creates custom subject and accepts a real 3-page PDF',async({page})=>{
 await page.goto('./?demo=1#/projects/new')
 await page.getByRole('textbox',{name:'Name'}).fill('Topology Exercises')
 await page.getByRole('textbox',{name:'Goal'}).fill('Construct counterexamples and prove compactness results.')
 await page.getByRole('button',{name:'Add subject'}).click()
 const subject=page.getByRole('region',{name:'New subject'})
 await subject.getByRole('textbox',{name:'Subject name'}).fill('Topology II')
 await subject.getByRole('button',{name:'Add subject'}).click()
 await expect(page.getByRole('radio',{name:'Topology II'})).toHaveAttribute('aria-checked','true')
 await page.locator('input[type=file]').setInputFiles('tests/fixtures/sample.pdf')
 await expect(page.getByText('sample.pdf')).toBeVisible()
 await page.getByRole('button',{name:'Create project'}).click()
 await expect(page).toHaveURL(/#\/p\/topology-exercises$/,{timeout:30000})
 await expect(page.getByText(/Project created/)).toBeVisible()
})
test('rejects non-PDF files without creating a project',async({page})=>{
 await page.goto('./?demo=1#/projects/new')
 await page.getByRole('textbox',{name:'Name'}).fill('Rejected Upload')
 await page.getByRole('textbox',{name:'Goal'}).fill('A small test.')
 await page.locator('input[type=file]').setInputFiles({name:'not-a-pdf.txt',mimeType:'text/plain',buffer:Buffer.from('a text document')})
 await expect(page.getByRole('alert')).toContainText('Choose a PDF')
 await expect(page.getByRole('button',{name:'Create project'})).toBeDisabled()
})
