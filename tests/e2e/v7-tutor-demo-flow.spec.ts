import {expect,test} from '@playwright/test'
import {choosePadCheckpoint} from './helpers/pad-picker'

const route=(cp:string,flag=true)=>'/lemma/?demo=1&flags=v7Shell,padLocal'+(flag?',tutorManualDemo':'')+'#/pad?path=real-analysis&checkpoint='+cp

test('manual tutor keeps drafts across checkpoints and reload without sending anything',async({page,context})=>{
 await context.grantPermissions(['clipboard-read','clipboard-write'])
 await page.goto(route('CP4',false))
 await expect(page.getByRole('heading',{level:2,name:'CP4 · Compactness'})).toBeVisible()
 await expect(page.getByRole('button',{name:'Open manual tutor'})).toHaveCount(0)
 await page.goto(route('CP4'))
 const open=page.getByRole('button',{name:'Open manual tutor'})
 const dialog=page.getByRole('dialog',{name:'Manual tutor'})
 const show=async()=>{await open.click();await expect(dialog.getByLabel('Question',{exact:true})).toBeVisible()}
 await show()
 await dialog.getByLabel('Question',{exact:true}).fill('Why does the subcover suffice?')
 await dialog.getByRole('checkbox',{name:/checkpoint’s objective/}).check()
 await page.keyboard.press('Escape')
 await expect(dialog).toBeHidden()
 await expect(open).toBeFocused()
 await choosePadCheckpoint(page,'CP3')
 await expect(page.getByRole('heading',{level:2,name:'CP3 · Sequences'})).toBeVisible()
 await show()
 await expect(dialog.getByLabel('Question',{exact:true})).toHaveValue('')
 await dialog.getByRole('button',{name:'Close',exact:true}).click()
 await choosePadCheckpoint(page,'CP4')
 await expect(page.getByRole('heading',{level:2,name:'CP4 · Compactness'})).toBeVisible()
 await show()
 await expect(dialog.getByLabel('Question',{exact:true})).toHaveValue('Why does the subcover suffice?')
 await dialog.getByRole('button',{name:'Save question'}).click()
 await expect(dialog.getByText('Saved. Waiting for a reply.')).toBeVisible()
 const copied=await dialog.getByLabel('Text for your tutor').inputValue()
 expect(copied).toMatch(/^Why does the subcover suffice\?\n\n\S/)
 await dialog.getByRole('button',{name:'Copy for tutor'}).click()
 await expect(dialog.getByText('Question copied.')).toBeVisible()
 expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe(copied)
 await dialog.getByLabel('Paste reply').fill('A finite subcover is enough.')
 await dialog.getByRole('button',{name:'Preview import'}).click()
 await dialog.getByRole('button',{name:'Cancel import'}).click()
 await expect(dialog.getByLabel('Paste reply')).toHaveValue('A finite subcover is enough.')
 await dialog.getByRole('button',{name:'Preview import'}).click()
 await page.reload()
 await open.click()
 await expect(dialog.getByLabel('Paste reply')).toHaveValue('A finite subcover is enough.')
 await expect(dialog.getByRole('region',{name:'Import preview'})).toHaveCount(0)
 await expect(dialog.getByLabel('Text for your tutor')).toHaveValue(copied)
 await dialog.getByRole('button',{name:'Preview import'}).click()
 await dialog.getByRole('button',{name:'Confirm import'}).click()
 const reply=dialog.getByRole('article',{name:'Imported reply'})
 await expect(reply).toContainText('A finite subcover is enough.')
 await expect(dialog.getByLabel('Paste reply')).toHaveCount(0)
 await page.reload()
 await show()
 await expect(reply).toContainText('A finite subcover is enough.')
 await expect(dialog.getByLabel('Question',{exact:true})).toHaveValue('')
 expect(context.pages()).toHaveLength(1)
})
