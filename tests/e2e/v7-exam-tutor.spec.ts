import {expect,test} from '@playwright/test'
import {examActions,examAnswer,examPath,examThread,examTutor,importExamReply,saveExamIdea,sendExamQuestion} from './helpers/exam'

test('uses a separate exam conversation, times an item and lets the learner undo a saved idea',async({page})=>{
 await page.goto(examPath('/p/linear-algebra?tab=exam'))
 await page.getByRole('link',{name:'Start in tutor'}).click()
 await expect(examTutor(page)).toBeVisible()
 await expect(page).toHaveURL(/\/tutor\?.*exam=demo-exam-project-linear/)
 await examTutor(page).getByRole('button',{name:/Exam prep · Linear Algebra midterm/}).click()
 const coverage=page.getByRole('dialog',{name:'Exam coverage'})
 await expect(coverage.getByRole('heading',{name:'Coverage ledger'})).toBeVisible()
 await coverage.getByRole('button',{name:'Close',exact:true}).click()
 await sendExamQuestion(page,'Please test my diagonalization method.')
 await importExamReply(page,'Timed: 1 seconds\n\nWhen does a basis of eigenvectors exist?')
 await expect(examTutor(page).getByText(/Timed ·|Time up/)).toBeVisible()
 await expect(examTutor(page).getByText('Time up · you can still answer')).toBeVisible()
 await saveExamIdea(page,'How eigenspace dimensions determine diagonalizability')
 await page.getByRole('button',{name:'Undo',exact:true}).click()
 await expect(examTutor(page).getByRole('link',{name:/Idea saved:/})).toHaveCount(0)
 await sendExamQuestion(page,'The eigenspaces must span the whole vector space.')
 await expect(examTutor(page).getByText('Incorrect', {exact:true})).toHaveCount(0)
 await page.reload()
 await expect(examTutor(page).getByRole('log',{name:'Conversation'})).toContainText('The eigenspaces must span')
 await page.goto(examPath('/p/linear-algebra/cp/CP9/tutor'))
 await expect(page.getByText('Exam prep is active for this subject.')).toBeVisible()
 await expect(page.getByText('The eigenspaces must span', {exact:false})).toHaveCount(0)
})

test('offers memory and recap separately and shows the recap as exposure',async({page})=>{
 await page.goto(examPath(examThread))
 await sendExamQuestion(page,'Review row diagonalizability: read a recap. Give me one example.')
 await importExamReply(page,'In a diagonalizable matrix, the eigenspaces span the vector space. Try a fresh one?')
 await expect(examTutor(page).getByRole('button',{name:'Reading only'})).toBeVisible()
 const review=examTutor(page).getByRole('region',{name:/Review Decide diagonalizability/})
 await review.getByRole('button',{name:'Try from memory'}).click()
 await expect(examAnswer(page)).toHaveValue(/try from memory/)
 const menu=await examActions(page)
 await menu.getByRole('button',{name:/I have \d+ min/}).click()
 const budget=page.getByRole('dialog',{name:'Study time left'})
 await budget.getByLabel('Minutes available').fill('45')
 await budget.getByRole('button',{name:'Save',exact:true}).click()
 await expect(examTutor(page).getByRole('button',{name:'I have 45 min'})).toBeVisible()
})
