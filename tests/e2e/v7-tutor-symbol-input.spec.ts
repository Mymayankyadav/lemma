import {expect,test} from '@playwright/test';

// N227 (Owner): with the scratch pad on, the strip's pencil opens Scratch; Draw symbol (Detexify) is the plain answer's.
const prefix='/lemma/?demo=1&flags=v7Shell,v6Shell,-tutorScratch#';
const tutor=prefix+'/p/real-analysis/cp/CP4/tutor';

for(const [query,name,glyph] of [['infinty','Infinity','∞'],['upside-down A','For all','∀']]){
 test(`Symbol search accepts ${query} as an explicit, undoable choice`,async({page})=>{
  await page.setViewportSize({width:320,height:640});
  await page.goto(tutor);
  await page.getByRole('button',{name:'Write a question',exact:true}).click();
  const answer=page.getByRole('textbox',{name:'Your answer',exact:true});
  await answer.fill('A B');
  await answer.press('Home');
  await answer.press('ArrowRight');
  await answer.press('ArrowRight');
  const board=page.getByRole('group',{name:'Answer keyboard',exact:true});
  await board.getByRole('button',{name:'Maths symbols',exact:true}).click();
  await board.getByRole('button',{name:'Browse symbols',exact:true}).click();
  const picker=page.getByRole('dialog',{name:'Symbols',exact:true});
  const search=picker.getByRole('searchbox',{name:'Search symbols',exact:true});
  await search.fill(query);
  await expect(answer).toHaveText('A B');
  await search.press('ArrowDown');
  await expect(picker.getByRole('button',{name,exact:true})).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(picker).toHaveCount(0);
  await expect(answer).toBeFocused();
  await expect(answer).toHaveText('A '+glyph+'B');
  await answer.press('Control+z');
  await expect(answer).toHaveText('A B');
  await page.keyboard.type('x');
  await expect(answer).toHaveText('A xB');
 });
}

test('switching to the device keyboard releases a live symbol stroke when the picture scratchpad is disabled',async({page})=>{
  const customOnly='/lemma/?demo=1&flags=v7Shell,v6Shell,-tutorScratch#';
  await page.addInitScript(()=>Object.defineProperty(window,'Worker',{value:undefined,configurable:true}));
  await page.goto(customOnly+'/settings?section=tutor');
  await page.getByRole('switch',{name:'Draw single symbols',exact:true}).click();
  await page.goto(customOnly+'/p/real-analysis/cp/CP4/tutor');
  await page.getByRole('button',{name:'Write a question',exact:true}).click();
  const answer=page.getByRole('textbox',{name:'Your answer',exact:true});
  await answer.click();
  await page.getByRole('button',{name:'Draw symbol',exact:true}).click();
  const pad=page.getByRole('img',{name:'Draw one symbol',exact:true});
  const box=await pad.boundingBox();
  await page.mouse.move(box!.x+box!.width*.6,box!.y+box!.height*.25);
  await page.mouse.down();
  await page.mouse.move(box!.x+box!.width*.4,box!.y+box!.height*.5);
  await page.getByRole('button',{name:'Use device keyboard',exact:true}).evaluate((button:HTMLButtonElement)=>button.click());
  await page.mouse.up();
  await expect(pad).toHaveCount(0);
  await expect(answer).toHaveAttribute('inputmode','text');
  await page.getByRole('button',{name:'Use Lemma keyboard',exact:true}).click();
  await expect(page.getByRole('button',{name:'q',exact:true})).toBeVisible();
  await expect(pad).toHaveCount(0);
  await page.getByRole('button',{name:'Draw symbol',exact:true}).click();
  await expect(pad).toBeVisible();
  await expect(answer).toHaveValue('');
  await expect(page.getByRole('button',{name:/^Matches /})).toHaveCount(0);
});

test('Keep drawing accepts consecutive symbols at a textarea caret mid-answer',async({page})=>{
  const customOnly='/lemma/?demo=1&flags=v7Shell,v6Shell,-tutorScratch#';
  await page.addInitScript(()=>Object.defineProperty(window,'Worker',{value:undefined,configurable:true}));
  await page.goto(customOnly+'/settings?section=tutor');
  await page.getByRole('switch',{name:'Draw single symbols',exact:true}).click();
  await page.goto(customOnly+'/p/real-analysis/cp/CP4/tutor');
  await page.getByRole('button',{name:'Write a question',exact:true}).click();
  const answer=page.getByRole('textbox',{name:'Your answer',exact:true});
  await answer.fill('A B');
  await answer.press('Home');
  await answer.press('ArrowRight');
  await answer.press('ArrowRight');
  await page.getByRole('button',{name:'Draw symbol',exact:true}).click();
  const keep=page.getByRole('button',{name:'Keep drawing',exact:true});
  await keep.click();
  await expect(keep).toBeFocused();
  const pad=page.getByRole('img',{name:'Draw one symbol',exact:true});
  const draw=async()=>{
    const box=(await pad.boundingBox())!;
    const scale=Math.min(box.width/320,box.height/116);
    const x=box.x+(box.width-320*scale)/2,y=box.y+(box.height-116*scale)/2;
    await page.mouse.move(x+180*scale,y+20*scale);
    await page.mouse.down();
    await page.mouse.move(x+114*scale,y+50*scale,{steps:3});
    await page.mouse.move(x+180*scale,y+80*scale,{steps:3});
    await page.mouse.up();
    await page.getByRole('button',{name:'Matches Less than',exact:true}).click();
  };
  await draw();
  await expect(answer).toHaveValue('A <B');
  await expect(answer).toBeFocused();
  await expect(keep).toHaveAttribute('aria-pressed','true');
  await expect(pad).toBeVisible();
  await expect(pad.locator('polyline')).toHaveCount(0);
  await draw();
  await expect(answer).toHaveValue('A <<B');
  await expect(answer).toHaveJSProperty('selectionStart',4);
  await expect(keep).toHaveAttribute('aria-pressed','true');
});

test('searchable manual symbols work with the beta off and restore the exact typing caret',async({page})=>{
  const modelRequests:string[]=[];
  page.on('request',request=>{
    const url=new URL(request.url());
    if(url.pathname.includes('/models/tutor-symbols/')&&!url.searchParams.has('import'))modelRequests.push(url.href);
  });
  await page.setViewportSize({width:320,height:640});
  await page.goto(tutor);
  await page.getByRole('button',{name:'Write a question',exact:true}).click();
  const header=page.locator('.tutor-header');
  const title=header.getByText('Compactness',{exact:true});
  const light=header.getByRole('button',{name:/Tutor status:/});
  await expect(title).toBeInViewport({ratio:1});
  await expect(light).toBeInViewport({ratio:1});
  const [titleBox,lightBox]=await Promise.all([title.boundingBox(),light.boundingBox()]);
  expect(lightBox!.x).toBeGreaterThanOrEqual(titleBox!.x+titleBox!.width);
  expect(Math.abs(titleBox!.y+titleBox!.height/2-lightBox!.y-lightBox!.height/2)).toBeLessThan(2);
  const answer=page.getByRole('textbox',{name:'Your answer',exact:true});
  await answer.fill('A B');
  await page.keyboard.press('Home');
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('ArrowRight');
  const board=page.getByRole('group',{name:'Answer keyboard',exact:true});
  await board.getByRole('button',{name:'Draw symbol',exact:true}).click();
  const draw=page.getByRole('region',{name:'Symbol recognition'});
  await expect(draw.getByRole('link',{name:'Tutor settings'})).toBeVisible();
  await expect(draw.getByRole('img',{name:'Draw one symbol'})).toHaveCount(0);
  await draw.getByRole('button',{name:'Browse symbols',exact:true}).click();
  const picker=page.getByRole('dialog',{name:'Symbols',exact:true});
  await picker.getByRole('searchbox',{name:'Search symbols',exact:true}).fill('not element of');
  await picker.getByRole('button',{name:'Not an element of',exact:true}).click();
  await expect(answer).toHaveJSProperty('textContent','A ∉B');
  await expect(answer).toBeFocused();
  await page.keyboard.type('x');
  await expect(answer).toHaveJSProperty('textContent','A ∉xB');
  await page.keyboard.press('Control+z');
  await page.keyboard.press('Control+z');
  await expect(answer).toHaveJSProperty('textContent','A B');
  expect(modelRequests).toEqual([]);
  await board.getByRole('button',{name:'Maths symbols',exact:true}).click();
  await board.getByRole('button',{name:'Browse symbols',exact:true}).click();
  await expect(picker.getByRole('button',{name:'Recent',exact:true})).toBeVisible();
  await expect(picker.getByRole('button',{name:'Not an element of',exact:true})).toBeVisible();
  await picker.getByRole('button',{name:'All symbols',exact:true}).click();
  await picker.getByRole('button',{name:'Greek',exact:true}).click();
  await expect(picker.getByRole('button',{name:'Epsilon',exact:true})).toBeVisible();
});

test('Settings opt-in exposes the symbol pad while unavailable runtime keeps the catalogue usable',async({page})=>{
  await page.setViewportSize({width:320,height:640});
  await page.addInitScript(()=>{
    Object.defineProperty(window,'Worker',{value:undefined,configurable:true});
    document.addEventListener('DOMContentLoaded',()=>{document.documentElement.style.fontSize='160%';});
  });
  await page.goto(prefix+'/settings?section=tutor');
  const preference=page.getByRole('switch',{name:'Draw single symbols',exact:true});
  const auto=page.getByRole('switch',{name:'Automatic insertion when qualified',exact:true});
  await expect(preference).not.toBeChecked();
  await expect(auto).toBeDisabled();
  await preference.click();
  await expect(preference).toBeChecked();
  await auto.click();
  await expect(auto).toBeChecked();
  await page.goto(tutor);
  await page.getByRole('button',{name:'Write a question',exact:true}).click();
  await page.getByRole('textbox',{name:'Your answer',exact:true}).click();
  await page.getByRole('button',{name:'Draw symbol',exact:true}).click();
  const draw=page.getByRole('region',{name:'Symbol recognition'});
  await expect(draw.getByRole('img',{name:'Draw one symbol'})).toBeInViewport({ratio:1});
  await expect(page.locator('.tutor-header')).toBeInViewport({ratio:1});
  await expect(page.getByRole('textbox',{name:'Your answer',exact:true})).toBeInViewport({ratio:1});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1);
  await expect(draw.getByText('Recognition unavailable. Browse symbols.',{exact:true})).toBeVisible();
  await draw.getByRole('button',{name:'Browse symbols',exact:true}).click();
  const picker=page.getByRole('dialog',{name:'Symbols',exact:true});
  await picker.getByRole('searchbox',{name:'Search symbols',exact:true}).fill('for all');
  await picker.getByRole('button',{name:'For all',exact:true}).click();
  await expect(page.getByRole('textbox',{name:'Your answer',exact:true})).toHaveJSProperty('textContent','∀');
  await expect(page.getByRole('button',{name:'q',exact:true})).toBeVisible();

  await page.getByRole('button',{name:'Draw symbol',exact:true}).click();
  const canvas=draw.getByRole('img',{name:'Draw one symbol'});
  const box=await canvas.boundingBox();
  const scale=Math.min(box!.width/320,box!.height/116);
  const left=box!.x+(box!.width-320*scale)/2;
  const top=box!.y+(box!.height-116*scale)/2;
  await page.mouse.move(left+180*scale,top+20*scale);
  await page.mouse.down();
  await page.mouse.move(left+114*scale,top+50*scale,{steps:3});
  await page.mouse.move(left+180*scale,top+80*scale,{steps:3});
  await page.mouse.up();
  const match=draw.getByRole('group',{name:'Matches',exact:true}).getByRole('button',{name:'Matches Less than',exact:true});
  const extension=draw.getByRole('group',{name:'Could become',exact:true}).getByRole('button',{name:'Could become Less than or equal to',exact:true});
  await expect(match).toBeInViewport({ratio:1});
  await expect(extension).toBeInViewport({ratio:1});
  const [matchBox,extensionBox,afterDrawing]=await Promise.all([match.boundingBox(),extension.boundingBox(),canvas.boundingBox()]);
  expect(matchBox!.y).toBe(extensionBox!.y);
  expect(extensionBox!.x).toBeGreaterThan(matchBox!.x+matchBox!.width);
  expect(Math.abs(afterDrawing!.y-box!.y)).toBeLessThanOrEqual(1);
  await expect(canvas).toBeInViewport({ratio:1});
  await expect(page.locator('.tutor-header')).toBeInViewport({ratio:1});
  await extension.click();
  await expect(page.getByRole('textbox',{name:'Your answer',exact:true})).toHaveJSProperty('textContent','∀≤');
  await expect(page.getByRole('button',{name:'q',exact:true})).toBeVisible();
});
