import {expect,test} from '@playwright/test'
import {examActions,examPath,examThread,examTutor,importExamReply,saveExamIdea,sendExamQuestion} from './helpers/exam'

test('pauses exam prep, resumes its separate conversation, finishes and drafts an idea in Inbox',async({page})=>{
 await page.goto(examPath(examThread))
 await sendExamQuestion(page,'Please check eigenspaces first.')
 await importExamReply(page,'Timed: 120 seconds\n\nWhen does an eigenbasis exist?')
 await sendExamQuestion(page,'The dimensions of the eigenspaces must sum to the dimension of the space.')
 await importExamReply(page,'Score: diagonalizability · correct · 2/2 · independent\n\nFind an eigenbasis before trying an unfamiliar example.')
 await expect(examTutor(page).getByRole('button',{name:'Independent · 2/2',exact:true})).toHaveCount(1)
 await saveExamIdea(page,'Check dimensions before an eigenbasis')
 await examTutor(page).getByRole('button',{name:'Back to study',exact:true}).click()
 const returned=page.getByRole('region',{name:'Return to study'})
 await expect(returned).toContainText('Back to Linear Algebra')
 await expect(returned.getByRole('link',{name:'Continue studying'})).toBeVisible()
 await page.getByRole('button',{name:'Exam prep',exact:true}).click()
 await page.getByRole('link',{name:'Start in tutor'}).click()
 await expect(examTutor(page).getByRole('log',{name:'Conversation'})).toContainText('Please check eigenspaces first.')
 const actions=await examActions(page)
 await actions.getByRole('button',{name:'Finish exam…'}).click()
 await page.getByRole('dialog',{name:'Finish exam',exact:true}).getByRole('button',{name:'Yes',exact:true}).click()
 await expect(returned).toBeVisible()
 await returned.getByRole('link',{name:'Card ideas (1)'}).click()
 const ideas=page.getByRole('region',{name:'Card ideas'})
 await expect(ideas).toContainText('Check dimensions before an eigenbasis')
 await ideas.getByRole('button',{name:'Draft',exact:true}).click()
 await page.getByRole('dialog',{name:'Draft card',exact:true}).getByRole('button',{name:'Send to Inbox'}).click()
 await expect(ideas.getByRole('link',{name:'Waiting in Inbox'})).toBeVisible()
 await expect(ideas.getByRole('button',{name:'Draft',exact:true})).toHaveCount(0)
 await ideas.getByRole('link',{name:'Waiting in Inbox'}).click()
 await expect(page.getByText('Check dimensions before an eigenbasis',{exact:true}).first()).toBeVisible()
 await page.getByRole('button',{name:'Approve',exact:true}).click()
 const undo=page.getByRole('button',{name:'Undo',exact:true})
 await expect(undo).toBeVisible()
 await expect(undo).toHaveCount(0,{timeout:9000})
 await page.goto(examPath('/p/linear-algebra?tab=cards&cards=ideas'))
 await expect(page.getByRole('link',{name:/Added as N\d+/})).toBeVisible()
})
