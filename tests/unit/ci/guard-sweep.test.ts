import {describe,expect,it} from 'vitest'
// @ts-expect-error plain ESM script
import {lastAgentActivity,isLeaseExpired,parsePlan,needsReviewIntervals,analysePlan,buildMetrics,renderMetricsBody,filterSince,parseSince,v14Start} from '../../../scripts/ci/sweep.mjs'

const H=3600e3
const t0=new Date('2026-11-04T10:00:00Z').getTime()
describe('sweep: lease-expired without a lease timestamp',()=>{
 it('counts commits and the PR Agent\'s own comments, not other agents\' comments',()=>{
  const a=lastAgentActivity({agent:'lemma-1',createdAt:'2026-11-04T10:00:00Z',commitDates:['2026-11-04T10:30:00Z'],comments:[
   {body:'Done: x\nAgent: lemma-1',created_at:'2026-11-04T11:00:00Z'},
   {body:'Approve · Agent: lemma-2',created_at:'2026-11-04T12:30:00Z'},
   {body:'status\nAgent: lemma-9',created_at:'2026-11-04T12:40:00Z'}]})
  expect(a).toBe(new Date('2026-11-04T11:00:00Z').getTime())
  expect(isLeaseExpired({lastActivity:a,now:a+H-1})).toBe(false)
  expect(isLeaseExpired({lastActivity:a,now:a+H})).toBe(true)
 })
 it('a new PR is not expired and activity renews it',()=>{
  const created=lastAgentActivity({agent:'x',createdAt:'2026-11-04T10:00:00Z'})
  expect(created).toBe(t0)
  expect(isLeaseExpired({lastActivity:created,now:t0+H-1})).toBe(false)
  const renewed=lastAgentActivity({agent:'x',createdAt:'2026-11-04T10:00:00Z',commitDates:['2026-11-04T12:50:00Z']})
  expect(isLeaseExpired({lastActivity:renewed,now:t0+3.5*H})).toBe(false)
 })
 it('an unsigned comment or a comment from another Agent is not activity from the PR Agent',()=>{
  const a=lastAgentActivity({agent:'lemma-1',createdAt:'2026-11-04T10:00:00Z',comments:[{body:'looks fine',created_at:'2026-11-04T12:00:00Z'},{body:'Taking over: Agent lemma-5',created_at:'2026-11-04T12:10:00Z'}]})
  expect(a).toBe(t0)
 })
})
describe('sweep: run plans and agent-metrics',()=>{
 const T0='2026-11-04T10:00:00Z'
 const t0=new Date(T0).getTime()
 const now=new Date('2026-11-04T13:00:00Z').getTime()
 it('parses a Plan with and without a Result, ignoring a connector footer',()=>{
  const p=parsePlan('Plan · Agent: lemma-2: 1) review #821 2) continue #818 3) top NEXT item\nResult: 1) done 2) skipped because CI red 3) done\n\n---\n_Generated by Claude Code_')
  expect(p.agent).toBe('lemma-2')
  expect(p.steps).toEqual(['review #821','continue #818','top NEXT item'])
  expect(p.results).toEqual(['done','skipped because CI red','done'])
  const q=parsePlan('Plan · Agent: chat-3#k7q3: 1) continue #820')
  expect(q.steps).toEqual(['continue #820'])
  expect(q.results).toBeNull()
  expect(parsePlan('just a comment')).toBeNull()
  expect(parsePlan('Result: 1) done')).toBeNull()
 })
 it('needs-review intervals come from the label events and end at an unlabel or close',()=>{
  const ev=[{event:'labeled',label:{name:'needs-review'},created_at:'2026-11-04T09:00:00Z'},{event:'unlabeled',label:{name:'needs-review'},created_at:'2026-11-04T09:30:00Z'},{event:'labeled',label:{name:'bug'},created_at:'2026-11-04T09:40:00Z'},{event:'labeled',label:{name:'needs-review'},created_at:'2026-11-04T10:00:00Z'}]
  const iv=needsReviewIntervals(ev,now)
  expect(iv).toHaveLength(2)
  expect(iv[0]).toEqual({from:new Date('2026-11-04T09:00:00Z').getTime(),to:new Date('2026-11-04T09:30:00Z').getTime()})
  expect(iv[1].to).toBeGreaterThan(now)
  expect(needsReviewIntervals([ev[3],{event:'closed',created_at:'2026-11-04T11:00:00Z'}],now)[0].to).toBe(new Date('2026-11-04T11:00:00Z').getTime())
 })
 it('plan-short: a needs-review PR by someone else existed and the plan has no review step',()=>{
  const nr=[{authorKey:'lemma-1',intervals:[{from:t0-3600e3,to:t0+3600e3}]}]
  const noReview=parsePlan('Plan · Agent: lemma-2: 1) continue #818 2) top NEXT item\nResult: 1) done 2) done')
  expect(analysePlan({plan:noReview,createdAt:T0,now,needsReviewPrs:nr}).planShort).toBe(true)
  const withReview=parsePlan('Plan · Agent: lemma-2: 1) review #821 2) continue #818\nResult: 1) done 2) done')
  expect(analysePlan({plan:withReview,createdAt:T0,now,needsReviewPrs:nr}).planShort).toBe(false)
  // the agent's own needs-review PR does not count, nor one that was not labelled yet at plan time
  expect(analysePlan({plan:parsePlan('Plan · Agent: lemma-1: 1) continue #1'),createdAt:T0,now,needsReviewPrs:nr}).planShort).toBe(false)
  expect(analysePlan({plan:noReview,createdAt:T0,now,needsReviewPrs:[{authorKey:'lemma-1',intervals:[{from:t0+60e3,to:t0+3600e3}]}]}).planShort).toBe(false)
  expect(analysePlan({plan:noReview,createdAt:T0,now,needsReviewPrs:[]}).planShort).toBe(false)
 })
 it('no-result: a plan with no Result after the timer; the share of done steps otherwise',()=>{
  const open=parsePlan('Plan · Agent: lemma-2: 1) review #1 2) continue #2')
  expect(analysePlan({plan:open,createdAt:T0,now:t0+89*60e3,noResultMin:90}).noResult).toBe(false)
  expect(analysePlan({plan:open,createdAt:T0,now:t0+91*60e3,noResultMin:90}).noResult).toBe(true)
  // shortened timer for a test, then the default is back
  expect(analysePlan({plan:open,createdAt:T0,now:t0+3*60e3,noResultMin:2}).noResult).toBe(true)
  expect(analysePlan({plan:open,createdAt:T0,now:t0+3*60e3}).noResult).toBe(false)
  const done=parsePlan('Plan · Agent: lemma-2: 1) review #1 2) continue #2 3) bug\nResult: 1) done 2) skipped because CI red 3) done')
  const a=analysePlan({plan:done,createdAt:T0,now})
  expect([a.planned,a.done,a.noResult,a.share]).toEqual([3,2,false,2/3])
 })
 it('counts only activity after the v1.4 merge: older commits, reviews and plans are not credited',()=>{
  const since=new Date('2026-11-05T03:00:00Z').getTime()
  const old=since-3600e3, fresh=since+3600e3
  const commits=filterSince([{agent:'lemma-2',at:old},{agent:'lemma-2',at:old},{agent:'lemma-2',at:fresh}],since)
  const m=buildMetrics({plans:filterSince([{agent:'lemma-2',at:old,planned:2,done:2,planShort:false,noResult:false}],since),reviews:filterSince([{agent:'lemma-2',at:old}],since),commits,now:fresh+60e3})
  expect(m.rows.find((r:any)=>r.agent==='lemma-2')).toMatchObject({runs:0,planned:0,reviews:0,commits:1})
  expect(filterSince([{at:since}],since)).toHaveLength(1)
  const body=renderMetricsBody(m.markdown,fresh,since)
  expect(parseSince(body)).toBe(since)
  expect(body).toContain('Only activity since 2026-11-05T03:00:00.000Z (the v1.4 merge) is counted')
  expect(parseSince('no marker')).toBeNull()
 })
 it('finds the v1.4 start as the oldest commit of the newest run of v1.4 commits',()=>{
  const c=(v14:boolean,date:string)=>({v14,date})
  expect(v14Start([c(true,'2026-11-05T05:00:00Z'),c(true,'2026-11-05T03:00:00Z'),c(false,'2026-11-04T10:00:00Z'),c(false,'2026-11-04T09:00:00Z')])).toBe(new Date('2026-11-05T03:00:00Z').getTime())
  expect(v14Start([c(false,'2026-11-04T10:00:00Z')])).toBeNull()
  expect(v14Start([])).toBeNull()
 })
 it('rows only for valid names; other names are summed on one line',()=>{
  const m=buildMetrics({plans:[{agent:'ChatGPT',at:now,planned:1,done:1,planShort:false,noResult:false}],reviews:[{agent:'selftest-a',at:now}],commits:[{agent:'ChatGPT',at:now},{agent:'ChatGPT',at:now},{agent:'lemma-1',at:now}],now})
  expect(m.rows.map((r:any)=>r.agent)).toEqual(['lemma-1'])
  expect(m.markdown).not.toContain('| chatgpt |')
  expect(m.markdown).toContain('Activity under invalid names (not counted above): chatgpt (3), selftest-a (1).')
 })
 it('builds the per-agent table (base names, 24 h columns)',()=>{
  const day=24*3600e3
  const plans=[{agent:'lemma-2',at:now-3600e3,planned:3,done:2,planShort:true,noResult:false},{agent:'lemma-2',at:now-2*day,planned:2,done:0,planShort:false,noResult:true},{agent:'chat-3#k7q3',at:now-3600e3,planned:1,done:1,planShort:false,noResult:false},{agent:'chat-3#zzzz',at:now-2*day,planned:0,done:0,planShort:false,noResult:false}]
  const m=buildMetrics({plans,reviews:[{agent:'lemma-2',at:now-3600e3},{agent:'lemma-2',at:now-3*day}],commits:[{agent:'chat-3#k7q3',at:now-60e3}],now})
  const l2=m.rows.find((r:any)=>r.agent==='lemma-2')
  expect(l2).toMatchObject({runs:2,plans:2,planned:5,done:2,planShort:1,noResult:1,reviews:2,reviews24:1,runs24:1,commits:0})
  const c3=m.rows.find((r:any)=>r.agent==='chat-3')
  expect(c3).toMatchObject({runs:2,plans:1,planned:1,done:1,commits:1,commits24:1})
  expect(m.markdown).toContain('| lemma-2 | 2 | 2 | 5 | 2 | 40% | 1 | 1 | 2 | 0 | 1 | 1 | 0 |')
  expect(m.markdown.split('\n')[0]).toContain('plan-short')
  expect(renderMetricsBody(m.markdown,now)).toContain('Not work; do not edit')
 })
})
