import {describe,expect,it} from 'vitest'
import {readFileSync} from 'node:fs'
// @ts-expect-error plain ESM script
import {parseVerdict,evaluateMerge} from '../../../scripts/ci/approve.mjs'
// @ts-expect-error plain ESM script
import {botTokenViolations} from '../../../scripts/ci/lib.mjs'

const HEAD='2026-11-04T10:00:00Z'
const c=(id:number,body:string,at:string,assoc='OWNER')=>({id,body,created_at:at,author_association:assoc})
const base=(over:any={})=>({
 pr:{number:9,title:'N1 fix it',body:'Agent: lemma-1 · Item: N1\n\nbody',draft:false,state:'open',baseRef:'main',headSha:'abc',headRepo:'o/r',labels:[]},
 defaultBranch:'main',repo:'o/r',comments:[] as any[],headCommitDate:HEAD,
 checks:{'fast-gate':'success',scope:'success'},s0:[] as number[],...over,
})
const ev=(over:any={})=>evaluateMerge(base(over))
const approve=(agent:string,at='2026-11-04T10:05:00Z',id=1)=>c(id,`Approve · Agent: ${agent}`,at)

describe('review verdict comments',()=>{
 it('parses exactly the two formats',()=>{
  expect(parseVerdict('Approve · Agent: lemma-2')).toEqual({kind:'approve',agent:'lemma-2'})
  expect(parseVerdict('  Approve · Agent: lemma-2  \n')).toEqual({kind:'approve',agent:'lemma-2'})
  expect(parseVerdict('Changes requested · Agent: lemma-2: rename X\nand add a test')).toEqual({kind:'changes',agent:'lemma-2',what:'rename X\nand add a test'})
  expect(parseVerdict('Approve · Agent: lemma-2\nbut I have doubts')).toBeNull()
  // connectors append a footer after a --- line: ignored
  expect(parseVerdict('Approve · Agent: lemma-2\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_')).toEqual({kind:'approve',agent:'lemma-2'})
  expect(parseVerdict('Changes requested · Agent: lemma-2: fix X\n\n---\n_footer_')).toEqual({kind:'changes',agent:'lemma-2',what:'fix X'})
  expect(parseVerdict('looks ok\n---\nApprove · Agent: lemma-2')).toBeNull()
  expect(parseVerdict('Approved · Agent: lemma-2')).toBeNull()
  expect(parseVerdict('Approve')).toBeNull()
  expect(parseVerdict('Changes requested · Agent: lemma-2')).toBeNull()
  expect(parseVerdict('Done: x / Pending: - / Next: -\nAgent: lemma-2')).toBeNull()
 })
})

describe('when CI merges (self-test scenarios)',()=>{
 it('merges: approved by a different Agent after the head commit, checks green, no label, no S0',()=>{
  const r=ev({comments:[approve('lemma-2')]})
  expect(r.merge).toBe(true)
  expect(r.reasons).toEqual([])
  expect(r.approval.agent).toBe('lemma-2')
 })
 it('does NOT merge a "review" by the same Agent name as the PR author, and says why',()=>{
  const r=ev({comments:[approve('lemma-1')]})
  expect(r.merge).toBe(false)
  expect(r.reasons.join(' ')).toContain('same Agent name as the PR author')
  expect(ev({comments:[approve('LEMMA-1')]}).merge).toBe(false)
 })
 it('a valid approval by another Agent merges even when the author also "approved" its own PR',()=>{
  const r=ev({comments:[approve('lemma-1'),approve('lemma-2','2026-11-04T10:06:00Z',2)]})
  expect(r.merge).toBe(true)
  expect(r.reasons).toEqual([])
 })
 it('an approval is voided by a later push; a fresh approval merges',()=>{
  const voided=ev({comments:[approve('lemma-2')],headCommitDate:'2026-11-04T10:30:00Z'})
  expect(voided.merge).toBe(false)
  expect(voided.reasons.join(' ')).toContain('void')
  expect(ev({comments:[approve('lemma-2'),approve('lemma-3','2026-11-04T10:40:00Z',2)],headCommitDate:'2026-11-04T10:30:00Z'}).merge).toBe(true)
 })
 it('does not merge while fast-gate or scope is not green on the head',()=>{
  expect(ev({comments:[approve('lemma-2')],checks:{'fast-gate':'pending',scope:'success'}}).merge).toBe(false)
  const r=ev({comments:[approve('lemma-2')],checks:{'fast-gate':'success',scope:'failure'}})
  expect(r.merge).toBe(false)
  expect(r.reasons.join(' ')).toContain('scope is failure')
  expect(ev({comments:[approve('lemma-2')],checks:{'fast-gate':'success'}}).merge).toBe(false)
 })
 it('changes requested: adds the label, cancels an earlier approval, and the label blocks until the author pushes',()=>{
  const changes=c(2,'Changes requested · Agent: lemma-3: add a test','2026-11-04T10:10:00Z')
  const r=ev({comments:[approve('lemma-2'),changes]})
  expect(r.merge).toBe(false)
  expect(r.addChangesLabel).toBe(true)
  expect(r.reasons.join(' ')).toContain('changes were requested by lemma-3: add a test')
  // an approval after the request does not help while the label is there
  const again=ev({comments:[changes,approve('lemma-2','2026-11-04T10:20:00Z',3)],pr:{...base().pr,labels:['changes-requested']}})
  expect(again.merge).toBe(false)
  // the author pushes (head commit after the request; label removed by labels.yml): a fresh approval merges
  const fixed=ev({comments:[changes,approve('lemma-2','2026-11-04T10:50:00Z',3)],headCommitDate:'2026-11-04T10:40:00Z'})
  expect(fixed.addChangesLabel).toBe(false)
  expect(fixed.merge).toBe(true)
 })
 it('an S0 freeze blocks every PR except the incident\'s own fix PR',()=>{
  const r=ev({comments:[approve('lemma-2')],s0:[807]})
  expect(r.merge).toBe(false)
  expect(r.reasons.join(' ')).toContain('#807')
  const fix=ev({comments:[approve('lemma-2')],s0:[807],pr:{...base().pr,title:'incident #807 fix the token'}})
  expect(fix.merge).toBe(true)
  expect(ev({comments:[approve('lemma-2')],s0:[807],pr:{...base().pr,title:'incident #12 other'}}).merge).toBe(false)
 })
 it('only owners/members/collaborators can approve',()=>{
  expect(ev({comments:[c(1,'Approve · Agent: lemma-2','2026-11-04T10:05:00Z','NONE')]}).merge).toBe(false)
  expect(ev({comments:[c(1,'Approve · Agent: lemma-2','2026-11-04T10:05:00Z','CONTRIBUTOR')]}).merge).toBe(false)
  expect(ev({comments:[c(1,'Approve · Agent: lemma-2','2026-11-04T10:05:00Z','COLLABORATOR')]}).merge).toBe(true)
 })
 it('never merges rules:, revert, calibration, draft, closed, other-base or CI PRs',()=>{
  const ok=[approve('lemma-2')]
  for (const title of ['rules: x','revert #5','ci: perf calibration 2026-11-04','random title']) expect(ev({comments:ok,pr:{...base().pr,title}}).merge).toBe(false)
  expect(ev({comments:ok,pr:{...base().pr,draft:true}}).merge).toBe(false)
  expect(ev({comments:ok,pr:{...base().pr,state:'closed'}}).merge).toBe(false)
  expect(ev({comments:ok,pr:{...base().pr,baseRef:'selftest/x'}}).merge).toBe(false)
  expect(ev({comments:ok,pr:{...base().pr,body:'Agent: ci · Item: revert'}}).merge).toBe(false)
  expect(ev({comments:ok,pr:{...base().pr,body:'no line one'}}).merge).toBe(false)
  expect(ev({comments:ok,pr:{...base().pr,headRepo:'fork/r'}}).merge).toBe(false)
 })
 it('works for PRs that still carry the old lease line',()=>{
  const r=ev({comments:[approve('lemma-2')],pr:{...base().pr,body:'Agent: lemma-1 · Item: N1 · Lease until 2026-11-04T16:07:00Z'}})
  expect(r.merge).toBe(true)
 })
 it('with no verdict at all nothing is attempted (no status comment is written)',()=>{
  const r=ev({comments:[c(1,'Done: pushed\nAgent: lemma-1','2026-11-04T10:05:00Z')]})
  expect(r.merge).toBe(false)
  expect(r.attempted).toBe(false)
 })
})

describe('review-merge workflow',()=>{
 const text=readFileSync('.github/workflows/review-merge.yml','utf8')
 it('is main-side only, never checks out PR code, and the lint allows its CI_BOT_TOKEN',()=>{
  expect(text).toMatch(/^\s{2}issue_comment:/m)
  expect(text).not.toMatch(/^\s{2}pull_request(_target)?:/m)
  expect(text).not.toMatch(/ref:\s*\$\{\{\s*github\.event\.(pull_request|issue)/)
  expect(text).not.toContain('head.sha')
  expect(botTokenViolations([{name:'review-merge.yml',text}])).toEqual([])
  expect(botTokenViolations([{name:'sweep.yml',text}]).length).toBeGreaterThan(0)
 })
 it('starts only for verdict comments on pull requests',()=>{
  expect(text).toContain("startsWith(github.event.comment.body, 'Approve')")
  expect(text).toContain("startsWith(github.event.comment.body, 'Changes requested')")
  expect(text).toContain('github.event.issue.pull_request')
 })
})
