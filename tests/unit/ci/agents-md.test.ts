import {describe,expect,it} from 'vitest'
import {readFileSync} from 'node:fs'

const md=readFileSync('AGENTS.md','utf8')
describe('AGENTS.md v2.0 contract',()=>{
 it('is version 2.0 and dated',()=>expect(md.split('\n')[0]).toMatch(/^# Lemma agent rules — version 2\.0 \(2026-11-06\)$/))
 it('has the nine steps in the specified order',()=>{
  const run=md.slice(md.indexOf('## Each run'),md.indexOf('## Claiming and PRs'))
  const steps=[...run.matchAll(/^(\d)\. (.*)$/gm)].map((m)=>[m[1],m[2]])
  expect(steps.map((s)=>s[0])).toEqual(['1','2','3','4','5','6','7','8','9'])
  expect(steps[0][1]).toMatch(/S0 incident/)
  expect(steps[1][1]).toMatch(/failing check, a `merge-conflict: FAILED` comment, or the changes-requested label: fix it/)
  expect(steps[1][1]).toMatch(/A conflicted PR gets no fast-gate run at all/)
  expect(steps[2][1]).toMatch(/Review one PR labelled needs-review that you did not author/)
  expect(steps[3][1]).toMatch(/Continue your own unfinished PR toward its Done.*Ready · Agent: <name>/)
  expect(steps[4][1]).toMatch(/S1 incident/)
  expect(steps[5][1]).toMatch(/bug \+ confirmed/)
  expect(steps[6][1]).toMatch(/top NEXT\.md item.*if you have fewer than 2 open PRs/)
  expect(steps[7][1]).toMatch(/without confirmed/)
  expect(steps[8][1]).toMatch(/end the run/)
  expect(run).toContain('After finishing a step, continue to the next applicable step in the same run.')
 })
 it('states the plan, names, one-PR-per-item and Ready rules',()=>{
  expect(md).toContain('A plan must include every applicable step; leaving one out is recorded.')
  expect(md).toContain('Plan · Agent: <name>: 1) … 2) … 3) …')
  expect(md).toContain('Result: 1) done|skipped because … 2) …')
  expect(md).toContain('Chat agents: at your first run, choose a 4-character tag')
  expect(md).toContain('chat-<n> is in use by session <tag> until <time>; pick another number')
  expect(md).toContain('never open a second PR for the item')
  expect(md).toContain('comment exactly `Ready · Agent: <your name>`')
  expect(md).toContain('Per agent only the latest verdict on the current head counts; duplicates are ignored.')
 })
 it('v1.5: migrations are additive only, with the exact escape hatch',()=>{
  const safety=md.slice(md.indexOf('## Safety'))
  expect(safety).toContain('Migrations are additive only: your PR merges straight to production.')
  expect(safety).toContain('Never edit, rename or delete an existing migration.')
  expect(safety).toContain('MIGRATION-ADDITIVE')
  expect(safety).toContain('Replaces function: <name> (reviewer verified signature and behaviour)')
 })
 it('v1.6: Ready is posted in the same run as the push, without waiting for checks',()=>{
  const run=md.slice(md.indexOf('## Each run'),md.indexOf('## Claiming and PRs'))
  expect(run).toMatch(/^4\. .*push and comment exactly `Ready · Agent: <name>` in the same run\. Do not wait for checks/m)
  const review=md.slice(md.indexOf('## Review and merge'),md.indexOf('## Communication'))
  expect(review).toContain('right after your last push, in the same run. Do not wait for checks')
  expect(review).toContain('CI re-evaluates when fast-gate and scope finish')
  expect(review).toContain('fixing it is step 2 of your next run')
 })
 it('v1.6: a split rewrites other items\' Needs: N<id> and may edit nothing else in them (#866)',()=>{
  const split=md.slice(md.indexOf('## Too big or stuck'),md.indexOf('## Stages'))
  expect(split).toContain('In every other item whose Needs lists N<id>, replace N<id> with the sub-item(s) that finish the work')
  expect(split).toContain('it fails a split that leaves any item needing N<id>')
 })
 it('v1.7: an item PR deletes its own NEXT.md block; ids missing from NEXT.md are done',()=>{
  const claim=md.slice(md.indexOf('## Claiming and PRs'),md.indexOf('## Too big or stuck'))
  expect(claim).toContain("An item PR also deletes its item's whole block from NEXT.md")
  expect(claim).toContain('NEXT-MD-DONE')
  expect(claim).toContain('An id in a Needs line that is no longer in NEXT.md is done.')
 })
 it('v1.9: agents leave CURRENT.md / NEXT.md-only conflicts to CI',()=>{
  const run=md.slice(md.indexOf('## Each run'),md.indexOf('## Claiming and PRs'))
  expect(run).toContain('Conflicts only in CURRENT.md or NEXT.md you never fix: CI merges main into your branch and keeps both sides')
  expect(run).toContain('your Ready and approvals still count')
  expect(run).toContain('Fix a conflict yourself only when CI\'s comment says it could not.')
 })
 it('v2.0: agents keep working, push rarely, and most PRs merge on Ready without review',()=>{
  const run=md.slice(md.indexOf('## Each run'),md.indexOf('## Claiming and PRs'))
  expect(run).toContain('Keep working: posting Ready, pushing, or checks still running are never reasons to end a run')
  expect(run).toContain('after Ready, take the next item (step 7)')
  const claim=md.slice(md.indexOf('## Claiming and PRs'),md.indexOf('## Too big or stuck'))
  expect(claim).toContain('- Limits: 2 open PRs per agent, at most 12 open PRs in total.')
  expect(claim).toContain('Put all your changes for a PR into one commit per run, including CURRENT.md and NEXT.md')
  const review=md.slice(md.indexOf('## Review and merge'),md.indexOf('## Communication'))
  expect(review).toContain('Most PRs need no review. CI squash-merges an item, bug or incident PR when all of these hold: your Ready is newer than your last push')
  expect(review).toContain('A review is required only when the PR changes `supabase/**`')
  expect(review).toContain('Request changes only for a real defect in the diff; never for a merge conflict')
  expect(md).toContain('A flag may default on only after Harden.')
 })
 it('tells agents nothing about merging, leases or the old label wait',()=>{
  expect(md).not.toMatch(/squash-merge, then|Lease until|do not wait for it/i)
  expect(md).not.toMatch(/^\s*[-\d.]+\s.*\bmerge (it|the PR)\b/im)
 })
})
